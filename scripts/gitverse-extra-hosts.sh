#!/usr/bin/env bash
# Resolve GitVerse hosts with the *host* DNS and write docker-compose.override.yml
# extra_hosts. Docker's 127.0.0.11 often cannot resolve internal API names.
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
config="${1:-$root/config.yml}"
out="${2:-$root/docker-compose.override.yml}"

if [[ ! -f "$config" ]]; then
  echo "gitverse-extra-hosts: no $config" >&2
  exit 1
fi

yaml_value() {
  local key="$1"
  awk -v key="$key" '
    $1 == key ":" {
      val = $0
      sub(/^[^:]+:[[:space:]]*/, "", val)
      gsub(/^["'\'']|["'\'']$/, "", val)
      print val
      exit
    }
  ' "$config"
}

host_of() {
  local url="$1"
  url="${url#http://}"
  url="${url#https://}"
  url="${url%%/*}"
  url="${url%%:*}"
  printf '%s' "$url"
}

ip_of() {
  local host="$1"
  local line=""
  line="$(getent ahostsv4 "$host" 2>/dev/null || true)"
  if [[ -z "$line" ]]; then
    line="$(getent hosts "$host" 2>/dev/null || true)"
  fi
  local ip
  ip="$(printf '%s\n' "$line" | awk '{print $1; exit}')"
  if [[ -z "$ip" ]] && command -v python3 >/dev/null 2>&1; then
    ip="$(python3 -c 'import socket,sys; print(socket.gethostbyname(sys.argv[1]))' "$host" 2>/dev/null || true)"
  fi
  printf '%s' "$ip"
}

hosts_seen=" "
lines=""
missing=0

add_url() {
  local url="$1"
  local host ip
  host="$(host_of "$url")"
  if [[ -z "$host" ]]; then
    echo "gitverse-extra-hosts: empty host for url '$url'"
    return 0
  fi
  case "$hosts_seen" in
    *" $host "*) return 0 ;;
  esac
  hosts_seen="$hosts_seen$host "
  ip="$(ip_of "$host")"
  if [[ -z "$ip" && -n "$api_ip" && "$host" == "$api_host" ]]; then
    ip="$api_ip"
    echo "gitverse-extra-hosts: using GITVERSE_API_IP for $host"
  fi
  if [[ -z "$ip" ]]; then
    echo "gitverse-extra-hosts: could not resolve $host on the host" >&2
    missing=1
    return 0
  fi
  lines="${lines}      - \"$host:$ip\""$'\n'
  echo "gitverse-extra-hosts: $host -> $ip"
}

api_url="$(yaml_value GITVERSE_API_URL)"
api_host="$(host_of "$api_url")"
api_ip="$(yaml_value GITVERSE_API_IP)"
add_url "$api_url"
add_url "$(yaml_value GITVERSE_BASE_URL)"

{
  echo "# generated by scripts/gitverse-extra-hosts.sh; do not commit"
  echo "services:"
  echo "  gitverse-notifier:"
  if [[ -z "$lines" ]]; then
    echo "    extra_hosts: []"
  else
    echo "    extra_hosts:"
    printf '%s' "$lines"
  fi
} > "$out"

echo "gitverse-extra-hosts: wrote $out"
if [[ -n "$api_host" && "$lines" != *"$api_host:"* ]]; then
  echo "gitverse-extra-hosts: $api_host is missing from extra_hosts; GitVerse comments will fail inside Docker" >&2
  exit 1
fi
if [[ "$missing" -ne 0 ]]; then
  echo "gitverse-extra-hosts: some hosts did not resolve; Docker may still fail GitVerse API lookups" >&2
fi
